const { Bot } = require('grammy');// Импортируем библиотеку Grammy
const bot = new Bot('токен бота из телеграмма');// для работы поменять текст на токен

// Обработчик команды /start
bot.command('start', async (ctx) => {
    // если у пользователя нету имени оно заменится на noName
    const userName = ctx.from.first_name || ctx.from.username || 'noName';
    
    // отправка сообщение после команды
    await ctx.reply(
        `👋 Привет, ${userName}!\n\n` +
        `Я бот для обработки текстовых сообщений. Мои возможности:\n` +
        `• Отвечаю на команду /start приветствием\n` +
        `• Переворачиваю любой отправленный текст задом наперед\n` +
        `• Помогаю командой /help\n\n` +
        `Попробуй написать мне что-нибудь!`
    );
});

// Обработчик команды /help
bot.command('help', async (ctx) => {
    // список команд для пользователя
    const helpText = 
        '**Список доступных команд:**\n\n' +
        '/start : Приветствие и описание возможностей бота\n' +
        '/help : Показывает этот список команд\n\n' +
        '**Другие сообщения:**\n' +
        'Любой текст : Бот отправит его в перевернутом виде';
    
    // Отправляем сообщение с парсинг модом 'Markdown' для красивого форматирования
    await ctx.reply(helpText, { parse_mode: 'Markdown' });
});

// Функция для переворачивания строки задом наперед
function reverseString(text) {
    // Разбиваем строку на массив символов, переворачиваем и соединяем обратно в стороку
    return text.split('').reverse().join('');
}

// Обработчик всех текстовых сообщений
bot.on('message:text', async (ctx) => {
    // Получаем текст сообщения
    const userText = ctx.message.text;
    
    // Проверяем, состоит ли сообщение только из пробелов или пустое
    if (!userText || userText.trim().length === 0) {
        await ctx.reply('Пожалуйста, введите текст');
        return;
    }
    
    // Переворачиваем текст
    const reversedText = reverseString(userText);
    
    // Отправляем перевернутый текст
    await ctx.reply(`🔄 ${reversedText}`);
});

// обработчик для не существующих команд
bot.on('message:entities', async (ctx) => {
    // Проверяем, является ли сообщение командой (начинается с /)
    const text = ctx.message.text || '';
    
    if (text.startsWith('/')) {
        // Отвечаем сообщением об отсутствии такой команды
        await ctx.reply(
            'Неизвестная команда. Используйте /help для списка доступных команд'
        );
    }
});